export type FishFamily = keyof typeof fishFamilies;

const familyByGenus = new Map<string, FishFamily>((Object.keys(fishFamilies) as FishFamily[]).flatMap(family => {
  const [, ...genera] = fishFamilies[family];
  return genera.map(genus => [genus, family]);
}));

export function familyOf(scientificName: string) {
  const [genus] = scientificName.split(' ', 1);
  const family = familyByGenus.get(genus);
  if (!family) throw new Error(`Missing fish family for ${scientificName}`);
  return family;
}
